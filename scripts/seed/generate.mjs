// Generates supabase/seed.sql from the design's demo data (D-02): the Lumio AS scenario, for the local
// development database only. It is the only source of demo rows — nothing is created by hand against a
// database. Run: node scripts/seed/generate.mjs
//
// Staff can sign in locally with the values in dev-credentials.mjs (the hosted project never runs this file).
import { createHash } from 'node:crypto'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { designData } from './design-data.mjs'
import { DEV_PASSWORD, DEV_TOTP } from './dev-credentials.mjs'

const D = designData()
const out = []
const sql = (s) => out.push(s)

/** A stable uuid per design id, so a re-run gives the same rows. */
export const uid = (ns, id) => {
  const h = createHash('md5').update(`${ns}:${id}`).digest('hex')
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`
}
const q = (v) => (v === null || v === undefined ? 'null' : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`)
const arr = (xs, type) => `array[${xs.map(q).join(', ')}]::${type}[]`
const ago = (days) => `now() - interval '${days} days'`
const digits = (s) => s.replace(/\D/g, '')
const emailOf = (id) => D.staffById[id].email

const PS = { 'Super-admin': 'admin', Sales: 'sales', Support: 'support', Finance: 'finance', Marketing: 'marketing', Project: 'project', 'Read-only analyst': 'analyst' }

sql(`-- generated by scripts/seed/generate.mjs from design-reference/sentral/project/admin-data.js — do not edit
-- Local development only (D-02). Staff sign in with the password and TOTP secret in the generator.
set session_replication_role = replica;
begin;
`)

// ---- visibility groups and teams (Settings › Visibility groups, Users and teams)
const root = `(select id from app.visibility_groups where parent_id is null)`
const groups = [['Sales', null], ['Sales Norway', 'Sales'], ['Public sector', 'Sales'], ['Support', null], ['Finance', null], ['Growth', null], ['Delivery', null]]
for (const [n, parent] of groups) {
  sql(`insert into app.visibility_groups (id, name, parent_id) values (${q(uid('group', n))}, ${q(n)}, ${parent ? q(uid('group', parent)) : root});`)
}
const groupOf = { Leadership: null, Sales: 'Sales Norway', Support: 'Support', Finance: 'Finance', Growth: 'Growth', Delivery: 'Delivery' }

// ---- staff: an auth user each (local password + TOTP), and the staff profile
for (const s of D.staff) {
  const id = uid('user', s.id)
  sql(`insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, raw_app_meta_data, raw_user_meta_data,
  created_at, updated_at, confirmation_token, recovery_token, email_change_token_new, email_change, email_change_token_current, reauthentication_token, phone_change, phone_change_token)
values ('00000000-0000-0000-0000-000000000000', ${q(id)}, 'authenticated', 'authenticated', ${q(s.email)}, extensions.crypt(${q(DEV_PASSWORD)}, extensions.gen_salt('bf')), now(),
  '{"provider":"email","providers":["email"]}', '{}', now(), now(), '', '', '', '', '', '', '', '');
insert into auth.identities (id, user_id, provider_id, provider, identity_data, created_at, updated_at, last_sign_in_at)
values (gen_random_uuid(), ${q(id)}, ${q(id)}, 'email', jsonb_build_object('sub', ${q(id)}, 'email', ${q(s.email)}, 'email_verified', true), now(), now(), now());
insert into auth.mfa_factors (id, user_id, friendly_name, factor_type, status, secret, created_at, updated_at)
values (${q(uid('factor', s.id))}, ${q(id)}, 'Authenticator', 'totp', 'verified', ${q(DEV_TOTP)}, now(), now());
insert into app.admins (email, id, role, name, initials, title, permission_set_id, group_id, locale, time_zone)
values (${q(s.email)}, ${q(uid('staff', s.id))}, ${q(s.id === 'tor' ? 'owner' : 'admin')}, ${q(s.name)}, ${q(s.ini)}, ${q(s.role)},
  (select id from app.permission_sets where key = ${q(PS[s.role])}), ${groupOf[s.team] ? q(uid('group', groupOf[s.team])) : root}, 'en', 'Europe/Oslo');`)
}
const teams = [['Sales Norway', 'tor', ['ingrid', 'eirik']], ['Support', 'magnus', ['hanna']], ['Growth', 'jonas', []], ['Delivery', 'emma', ['magnus']]]
for (const [n, mgr, members] of teams) {
  sql(`insert into app.teams (id, name, manager_id) values (${q(uid('team', n))}, ${q(n)}, ${q(uid('staff', mgr))});`)
  for (const m of [mgr, ...members]) sql(`insert into app.team_members (team_id, staff_id) values (${q(uid('team', n))}, ${q(uid('staff', m))});`)
}
for (const s of D.staff) {
  const t = teams.find(([, mgr, ms]) => mgr === s.id || ms.includes(s.id))
  if (t) sql(`update app.admins set team_id = ${q(uid('team', t[0]))} where id = ${q(uid('staff', s.id))};`)
}

// ---- products (the design's four applications)
for (const [i, p] of D.products.entries()) {
  sql(`insert into app.products (key, name, description, color, ink, ord) values (${q(p.id)}, ${q(p.name)}, ${q(p.desc)}, ${q(p.color)}, ${q(p.ink)}, ${(i + 1) * 10})
  on conflict (key) do update set name = excluded.name, description = excluded.description, color = excluded.color, ink = excluded.ink, ord = excluded.ord;`)
  sql(`insert into app.installations (product, api_url, public_key, enabled) values (${q(p.id)}, ${q('https://' + p.api.split('/')[0])}, ${q('local-stand-in-public-key-' + p.id)}, true);`)
}

// ---- labels
const orgLabels = [...new Set([...D.orgs.flatMap((o) => o.labels), 'Champion', 'Renewal Q4', 'Expansion', 'Pilot', 'Reference customer', 'Needs onboarding'])]
for (const [i, n] of orgLabels.entries()) sql(`insert into app.labels (id, entity, name, bg, ink, ord) values (${q(uid('label-org', n))}, 'organization', ${q(n)}, '#F2EAD6', '#5F5849', ${i * 10});`)
const personLabels = [...new Set(D.people.flatMap((p) => p.labels))]
for (const [i, n] of personLabels.entries()) sql(`insert into app.labels (id, entity, name, bg, ink, ord) values (${q(uid('label-person', n))}, 'person', ${q(n)}, '#F2EAD6', '#5F5849', ${i * 10});`)

// ---- customers: an account per organization, a tenant per product it uses, the subscription
for (const o of D.orgs) {
  const acct = uid('account', o.id)
  const orgnr = digits(o.orgnr)
  sql(`insert into app.accounts (id, name, org_number, created_at) values (${q(acct)}, ${q(o.name)}, ${q(orgnr)}, ${ago(o.signupDaysAgo)});`)
  for (const p of o.products) {
    const tenant = `${p}-${o.id}`
    sql(`insert into app.account_products (product, tenant_id, account_id, status, details, attribution, created_at)
  values (${q(p)}, ${q(tenant)}, ${q(acct)}, 'active', jsonb_build_object('employees', ${o.employees}, 'band', ${q(o.band)}), jsonb_build_object('source', ${q(o.source)}), ${ago(o.signupDaysAgo)});`)
    const trial = o.status === 'Trial'
    const cancelled = o.status === 'Cancelled'
    sql(`insert into app.subscriptions (product, tenant_id, plan, billing_interval, trial_started_at, trial_ends_at, confirmed_at, cancelled_at, cancel_effective_at, updated_at)
  values (${q(p)}, ${q(tenant)}, ${q(o.band)}, 'month', ${ago(o.signupDaysAgo)}, ${trial ? `${ago(o.signupDaysAgo)} + interval '30 days'` : `${ago(o.signupDaysAgo)} + interval '30 days'`},
  ${trial ? 'null' : `${ago(o.signupDaysAgo)} + interval '20 days'`}, ${cancelled ? ago(10) : 'null'}, ${cancelled ? ago(1) : 'null'}, now());`)
  }
  sql(`insert into app.organizations (id, name, org_number, account_id, city, fylke, industry, employees, source, ehf, csm_id, owner_id, labels, created_at, updated_at, brreg_synced_at)
  values (${q(uid('org', o.id))}, ${q(o.name)}, ${q(orgnr)}, ${q(acct)}, ${q(o.city)}, ${q(o.fylke)}, ${q(o.industry)}, ${o.employees}, ${q(o.source)}, ${o.ehf},
  ${q(uid('staff', o.csm))}, ${q(uid('staff', o.owner))}, ${arr(o.labels.map((l) => uid('label-org', l)), 'uuid')}, ${ago(o.signupDaysAgo)}, ${ago(Math.min(o.signupDaysAgo, 5))}, ${ago(((parseInt(o.id.slice(1), 10)) % 9) + 2)});`)
}
for (const o of D.orgs.filter((x) => x.parent)) sql(`update app.organizations set parent_id = ${q(uid('org', o.parent))} where id = ${q(uid('org', o.id))};`)

// ---- people; a customer's own users are also product members
const ctype = { Prospect: 'prospect', 'Trial user': 'trial_user', 'Customer user': 'customer_user', 'Former customer': 'former_customer' }
for (const p of D.people) {
  const o = D.orgById[p.org]
  const member = p.type === 'Customer user' || p.type === 'Trial user'
  if (member) {
    sql(`insert into app.members (product, tenant_id, user_id, role, email, name, active, updated_at) values ('orgpuls', ${q('orgpuls-' + o.id)}, ${q('u-' + p.id)},
  ${q(p.role === 'Daglig leder' ? 'daglig_leder' : p.role === 'Verneombud' ? 'verneombud' : 'avdelingsleder')}, ${q(p.email)}, ${q(p.name)}, true, now());`)
  }
  sql(`insert into app.people (id, name, email, phone, organization_id, title, contact_type, source, city, fylke, owner_id, labels, last_touch_at,
  member_product, member_tenant, member_user, created_at, updated_at)
  values (${q(uid('person', p.id))}, ${q(p.name)}, ${q(p.email)}, ${q(p.phone)}, ${q(uid('org', p.org))}, ${q(p.role)}, ${q(ctype[p.type])}, ${q(p.source)}, ${q(p.city)}, ${q(p.fylke)},
  ${q(uid('staff', p.owner))}, ${arr(p.labels.map((l) => uid('label-person', l)), 'uuid')}, ${ago(p.lastTouch)},
  ${member ? "'orgpuls'" : 'null'}, ${member ? q('orgpuls-' + o.id) : 'null'}, ${member ? q('u-' + p.id) : 'null'}, ${ago(60)}, ${ago(p.lastTouch)});`)
}

sql(`
commit;
set session_replication_role = origin;
`)

const target = fileURLToPath(new URL('../../supabase/seed.sql', import.meta.url))
writeFileSync(target, out.join('\n') + '\n')
console.log(`wrote ${target} (${out.length} statements)`)
